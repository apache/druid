// Blueprint 6 styles many components through CSS design tokens (--bp-*) that are generated with the
// stock Blueprint palette. The console uses its own palette (src/blueprint-overrides/common/_colors.scss),
// so this script re-declares every color token in terms of the palette variable of the same name, along with the
// typography, radius and timing tokens that correspond to Sass variables the console overrides.
// Run it again after upgrading Blueprint: `node script/generate-blueprint-token-overrides.mjs`

import fs from 'fs';

const TOKENS_DIR = 'node_modules/@blueprintjs/core/src/design-tokens/build';
const BLUEPRINT_COLORS = 'node_modules/@blueprintjs/colors/src/_colors.scss';
const OUTPUT = 'src/blueprint-overrides/_design-tokens.scss';

const LICENSE_HEADER = fs
  .readFileSync('src/blueprint-overrides/_index.scss', 'utf-8')
  .split('\n')
  .slice(0, 17)
  .join('\n');

// Map each stock Blueprint color (hex) to its Sass variable name
const colorVariableByHex = new Map();
for (const [, name, hex] of fs
  .readFileSync(BLUEPRINT_COLORS, 'utf-8')
  .matchAll(/^\$([a-z-]+\d?):\s*(#[0-9a-f]{6})\b/gim)) {
  if (!colorVariableByHex.has(hex.toLowerCase())) colorVariableByHex.set(hex.toLowerCase(), name);
}

// Non-color tokens that correspond to Sass variables the console overrides
const TOKEN_VARIABLES = {
  '--bp-typography-family-default': 'pt-font-family',
  '--bp-typography-family-mono': 'pt-font-family-monospace',
  '--bp-typography-size-body-small': 'pt-font-size-small',
  '--bp-typography-size-body-medium': 'pt-font-size',
  '--bp-typography-size-body-large': 'pt-font-size-large',
  '--bp-typography-line-height-default': 'pt-line-height',
  '--bp-surface-border-radius': 'pt-border-radius',
  '--bp-emphasis-transition-duration': 'pt-transition-duration',
};

function toPaletteExpression(value) {
  let replaced = false;
  const expression = value.replace(/#([0-9a-f]{6})([0-9a-f]{2})?\b/gi, (match, hex, alpha) => {
    const name = colorVariableByHex.get(`#${hex.toLowerCase()}`);
    if (!name) return match;
    replaced = true;
    if (!alpha) return `#{$${name}}`;
    const opacity = Math.round((parseInt(alpha, 16) / 255) * 1000) / 1000;
    return `#{rgba($${name}, ${opacity})}`;
  });
  return replaced ? expression : undefined;
}

function convertTokenFile(file) {
  const css = fs.readFileSync(`${TOKENS_DIR}/${file}`, 'utf-8');
  const blocks = [];
  for (const [, selector, body] of css.matchAll(/([^{}]+)\{([^}]*)\}/g)) {
    const declarations = [];
    const seen = new Set();
    for (const [, name, value] of body.matchAll(/(--bp-[a-z0-9-]+):\s*([^;]+);/g)) {
      if (seen.has(name)) continue; // Later definitions are relative color syntax derived from other tokens
      seen.add(name);
      const expression = TOKEN_VARIABLES[name]
        ? `#{$${TOKEN_VARIABLES[name]}}`
        : toPaletteExpression(value.trim());
      if (expression) declarations.push(`  ${name}: ${expression};`);
    }
    const cleanSelector = selector
      .replace(/\/\*[\s\S]*?\*\//g, '')
      .trim()
      .split(/\s*,\s*/)
      .map(part => part.replace(/"/g, "'").replace(/\.bp\d+-/g, '.#{$ns}-'))
      .join(',\n');
    if (declarations.length) blocks.push(`${cleanSelector} {\n${declarations.join('\n')}\n}`);
  }
  return blocks;
}

const output = [
  LICENSE_HEADER,
  '',
  '// Generated by script/generate-blueprint-token-overrides.mjs, do not edit directly.',
  '// Re-declares Blueprint design tokens with the console palette, must be loaded after Blueprint.',
  '',
  "@use 'common/colors' as *;",
  "@use 'common/variables' as *;",
  '',
  ...convertTokenFile('tokens.css'),
  '',
  ...convertTokenFile('tokens-dark.css'),
  '',
].join('\n');

fs.writeFileSync(OUTPUT, output);
// eslint-disable-next-line no-undef
console.log(`Wrote ${OUTPUT}`);
