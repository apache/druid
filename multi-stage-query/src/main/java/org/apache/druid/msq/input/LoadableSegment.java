package org.apache.druid.msq.input;

import com.google.common.util.concurrent.ListenableFuture;
import org.apache.druid.common.guava.FutureUtils;
import org.apache.druid.error.DruidException;
import org.apache.druid.query.SegmentDescriptor;
import org.apache.druid.segment.Segment;
import org.apache.druid.segment.loading.AcquireMode;
import org.apache.druid.segment.loading.AcquireSegmentAction;
import org.apache.druid.segment.loading.AcquireSegmentResult;
import org.apache.druid.server.SegmentManager;
import org.apache.druid.timeline.DataSegment;

import javax.annotation.Nullable;
import java.util.Optional;

//
/**
 * Pointer to some data that can be read as a {@link Segment}. These are contained by
 * {@link PhysicalInputSlice#getLoadableSegments()}, which are in turn generated by {@link InputSliceReader#attach}.
 *
 * These objects do not hold resources and do not have a lifecycle. They are just pointers to data that hasn't
 * been acquired yet. Once {@link #acquire(AcquireMode)} or {@link #acquireIfCached(AcquireMode)} is called, the
 * lifecycle begins.
 *
 * @see RegularLoadableSegment for segments loaded via {@link SegmentManager}
 * @see AdaptedLoadableSegment for segments adapted from other data sources
 */
public interface LoadableSegment
{
  /**
   * Returns the descriptor that is used to query this segment. The interval of this descriptor is particularly
   * important: it acts as a filter on the underlying segment.
   */
  SegmentDescriptor descriptor();

  /**
   * User-oriented description, suitable for inclusion in log or error messages.
   */
  @Nullable
  String description();

  /**
   * Attempts to acquire this segment if it is already cached locally.
   *
   * If the returned {@link Optional} is present, the caller is responsible for closing the {@link Segment}
   * when finished with it. If the returned {@link Optional} is empty, the segment is not cached and the caller
   * should use {@link #acquire(AcquireMode)} to load it.
   *
   * The {@code acquireMode} selects what counts as a cached hit and how the segment is mounted; see {@link AcquireMode}.
   * With {@link AcquireMode#PARTIAL} the returned {@link Segment} is mounted but, for a partial-download (virtual
   * storage) segment, may not be fully downloaded yet: its data is fetched on demand at cursor-build time. Callers must
   * therefore access it through the async API ({@link org.apache.druid.segment.CursorFactory#makeCursorHolderAsync})
   * rather than the synchronous {@code makeCursorHolder}, which refuses to download on a processing thread.
   *
   * If this method throws, it must leave the segment unacquired, holding nothing, so that it may still be acquired
   * later. {@link org.apache.druid.msq.querykit.ReadableInputQueue} relies on this: it treats a cached acquisition that
   * finds no room in the segment cache as a cache miss and loads the segment instead, and it keeps a segment whose
   * probe failed for any other reason among its unacquired segments.
   *
   * @return an Optional containing the cached Segment if available, or empty if not cached
   */
  Optional<Segment> acquireIfCached(AcquireMode acquireMode);

  /**
   * Acquire the actual segment. Non-blocking operation; the load (if one is needed) starts immediately. The returned
   * {@link AcquireSegmentAction} is an async handle: register it with cleanup machinery right away (safe at any
   * lifecycle point), wait for readiness via {@link AcquireSegmentAction#addReadyCallback} or
   * {@link AcquireSegmentAction#await}, then {@link AcquireSegmentAction#release()} to take ownership of the
   * {@link AcquireSegmentResult}. Closing the delivered {@link Segment} of the result releases everything associated
   * with the acquisition. Closing the action without releasing cancels an in-flight load or discards a delivered
   * result; close-after-release is a no-op, and closing before the action becomes ready fires any pending ready
   * callbacks (release/get then throw {@link org.apache.druid.common.asyncresource.AsyncResourceCanceledException}).
   * <p>
   * Load accounting is automatic: implementations install an {@link AcquireSegmentAction#setOnRelease} hook on the
   * returned action, so a successful release counts the load exactly once. The file itself is counted only when the
   * consumer calls {@link #countHandedOut()}.
   * <p>
   * The {@code acquireMode} selects how the segment is loaded; see {@link AcquireMode}. With {@link AcquireMode#PARTIAL}
   * the returned {@link Segment} is mounted but, for a partial-download (virtual storage) segment, may not be fully
   * downloaded yet: its data is fetched on demand at cursor-build time. Callers must therefore access it through the
   * async API ({@link org.apache.druid.segment.CursorFactory#makeCursorHolderAsync}) rather than the
   * synchronous {@code makeCursorHolder}, which refuses to download on a processing thread.
   *
   * If this method throws, the segment is left unacquired and may be acquired again later. If it returns an action
   * that then fails (its {@link AcquireSegmentAction#release()} throws), use {@link #abandonFailedAcquisition()} to
   * make the segment acquirable again.
   *
   * @throws DruidException if the segment has already been acquired
   */
  AcquireSegmentAction acquire(AcquireMode acquireMode);

  /**
   * Abandon an acquisition that failed to produce a {@link Segment}, so that {@link #acquire(AcquireMode)} may be
   * called again.
   *
   * Only valid when a prior {@link #acquire(AcquireMode)} returned an {@link AcquireSegmentAction} that failed.
   * Callers must have closed that action, and must be certain it handed out no {@link Segment}. (There is no need to
   * call this when {@link #acquire(AcquireMode)} itself throws; that leaves the segment unacquired already.)
   *
   * Used by {@link org.apache.druid.msq.querykit.ReadableInputQueue} to retry a load-ahead acquisition that ran out
   * of room in the segment cache, since load-ahead is an optimization that must not fail a query.
   *
   * @throws DruidException if the segment is not currently acquired
   */
  void abandonFailedAcquisition();

  /**
   * Counts this segment as a file read, using the row and byte counts recorded when it was acquired. The consumer
   * should only call this on segments that are handed out for processing to ensure counters don't overcount segments
   * acquired but subsequently skipped. Does nothing if the segment has not been acquired, or if it has already been
   * counted.
   */
  void countHandedOut();

  /**
   * Returns a future for the {@link DataSegment} object. For {@link RegularLoadableSegment}, the future is created
   * lazily when this method is first called, or when a segment is acquired through {@link #acquire(AcquireMode)}.
   * For {@link AdaptedLoadableSegment}, this returns a failed future.
   */
  ListenableFuture<DataSegment> dataSegmentFuture();

  /**
   * Returns the {@link DataSegment} object from {@link #dataSegmentFuture()}, blocking until it is available.
   * For {@link RegularLoadableSegment}, the object is guaranteed to be available once the segment has been acquired.
   * For {@link AdaptedLoadableSegment}, this throws an exception.
   */
  default DataSegment dataSegment()
  {
    return FutureUtils.getUnchecked(dataSegmentFuture(), false);
  }
}
